#!/usr/bin/env python3
"""Generates watch/source/tests/GoldenVectors.mc from protocol/vectors/vectors.json.

Usage: protocol/gen_mc_tests.py [--check]   (--check fails if the file is stale)
"""
import json, os, sys

ROOT = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(ROOT, "vectors", "vectors.json")
OUT = os.path.join(ROOT, "..", "watch", "source", "tests", "GoldenVectors.mc")


def lit(v):
    if isinstance(v, str):
        return json.dumps(v, ensure_ascii=False)
    if isinstance(v, list):
        return "[" + ", ".join(lit(x) for x in v) + "]"
    return str(v)


def render():
    data = json.load(open(SRC))
    out = ["// GENERATED by protocol/gen_mc_tests.py from protocol/vectors/vectors.json. Do not edit.",
           "import Toybox.Lang;", "import Toybox.StringUtil;", "import Toybox.Test;", "",
           "module GoldenVectors {",
           f"    const PROTO_SHA256 = \"{data['proto_sha256']}\";", "",
           "    function hexBytes(hex as String) as ByteArray {",
           "        return StringUtil.convertEncodedString(hex, {",
           "            :fromRepresentation => StringUtil.REPRESENTATION_STRING_HEX,",
           "            :toRepresentation => StringUtil.REPRESENTATION_BYTE_ARRAY",
           "        }) as ByteArray;", "    }", "",
           "    function same(a, b) as Boolean {",
           "        if (a instanceof Array) {",
           "            if (!(b instanceof Array) || a.size() != b.size()) { return false; }",
           "            for (var i = 0; i < a.size(); i++) {",
           "                if (!same(a[i], b[i])) { return false; }",
           "            }",
           "            return true;", "        }",
           "        return a.equals(b);", "    }", "",
           "    function check(logger as Test.Logger, name as String, hex as String, ints as Array, expected as Array) as Boolean {",
           "        var fromHex = Proto.decodeEnvelope(hexBytes(hex));",
           "        var fromInts = Proto.decodeMessage(ints);",
           "        if (fromHex == null || fromInts == null || !same(expected, fromHex) || !same(expected, fromInts)) {",
           "            logger.debug(\"golden vector mismatch: \" + name);",
           "            return false;", "        }",
           "        // The watch-side packer must reproduce the Kotlin transport list exactly.",
           "        if (!same(ints, Proto.pack(hexBytes(hex)))) {",
           "            logger.debug(\"pack mismatch: \" + name);",
           "            return false;", "        }",
           "        return true;", "    }", "}", ""]
    for v in data["vectors"]:
        out += ["(:test)", f"function testGolden_{v['name']}(logger as Test.Logger) as Boolean {{",
                f"    return GoldenVectors.check(logger, \"{v['name']}\",",
                f"        \"{v['hex']}\",", f"        {lit(v['transport'])},",
                f"        {lit(v['expected'])});", "}", ""]
    return "\n".join(out)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        if not os.path.exists(OUT) or open(OUT).read() != text:
            sys.exit("watch/source/tests/GoldenVectors.mc is stale; run protocol/gen_mc_tests.py")
    else:
        os.makedirs(os.path.dirname(OUT), exist_ok=True)
        open(OUT, "w").write(text)
